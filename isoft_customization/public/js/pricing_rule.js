// Pricing Rule: stop a save that would collide with another active rule, and offer
// the fixes right there. Server side: isoft_customization/pricing_rule_conflicts.py
// (the same check also runs in validate, so no other path can save a collision).
//
// A collision is two enabled rules that would both match one line with the same
// priority; ERPNext then refuses the line with "Multiple Price Rules exists with
// same criteria". Fixes offered, per colliding rule:
//   - remove the shared items from it (only when it has other items left)
//   - disable it
// and once for this rule:
//   - give it the lowest priority that wins over all of them

const PRC_API = "isoft_customization.pricing_rule_conflicts.";

frappe.ui.form.on("Pricing Rule", {
	validate(frm) {
		if (frm.doc.disable) return;
		// frappe waits for this promise and aborts the save if frappe.validated is false
		return new Promise((resolve) => {
			frappe.call({
				method: PRC_API + "check_conflicts",
				args: { doc: frm.doc },
				callback: (r) => {
					const res = r.message || {};
					if ((res.conflicts || []).length) {
						frappe.validated = false;
						prc_show_dialog(frm, res);
					}
					resolve();
				},
				// If the check itself fails the server-side validate still guards the save.
				error: () => resolve(),
			});
		});
	},
});

function prc_unit(apply_on, n) {
	const u = { "Item Code": [__("item"), __("items")], "Item Group": [__("item group"), __("item groups")], "Brand": [__("brand"), __("brands")] }[apply_on] || [__("item"), __("items")];
	return n === 1 ? u[0] : u[1];
}

function prc_show_dialog(frm, res) {
	const esc = frappe.utils.escape_html;
	const conflicts = res.conflicts;
	const done = {}; // rule -> "removed" | "disabled"

	const d = new frappe.ui.Dialog({
		title: __("This rule collides with {0} active pricing rule(s)", [conflicts.length]),
		size: "large",
		fields: [{ fieldtype: "HTML", fieldname: "body" }],
	});

	function card(c) {
		const n = c.shared.length;
		const left = c.total - n;
		const state = done[c.rule];
		const unit = prc_unit(c.apply_on, n);
		const can_remove = !c.promotional_scheme && left > 0;
		const shared = c.shared.slice(0, 12).map((s) => `<code>${esc(s)}</code>`).join(" ")
			+ (n > 12 ? ` <span class="text-muted">+${n - 12}</span>` : "");
		const rule = `<b>${esc(c.rule)}</b>`;
		let actions;
		if (state) {
			actions = `<div class="prc-done"><span class="indicator-pill green">${state === "disabled"
				? __("{0} disabled", [esc(c.rule)])
				: __("{0} {1} removed from {2}", [n, unit, esc(c.rule)])}</span></div>`;
		} else {
			// Each fix is a row: the button says what it does to which rule, the line
			// beside it says what that costs.
			let remove_row;
			if (can_remove) {
				remove_row = `<div class="prc-opt">
					<button class="btn btn-sm btn-default prc-act" data-rule="${esc(c.rule)}" data-action="remove">
						<i class="fa fa-minus-circle"></i> ${__("Remove {0} shared {1} from {2}", [n, unit, esc(c.rule)])}</button>
					<span class="prc-why">${__("{0} stays active for its other {1} {2}.", [rule, left, prc_unit(c.apply_on, left)])}</span>
				</div>`;
			} else {
				remove_row = `<div class="prc-opt is-off"><span class="prc-why">${c.promotional_scheme
					? __("Items cannot be removed here: {0} is generated by Promotional Scheme {1}.", [rule, esc(c.promotional_scheme)])
					: __("Removing is not possible: {0} holds only the shared {1}, so it would be left empty.", [rule, unit])}</span></div>`;
			}
			const lose = left > 0
				? __("The whole rule stops: <b>all {0} {1}</b> lose the {2} discount, not only the shared ones.", [c.total, prc_unit(c.apply_on, c.total), esc(c.discount)])
				: __("It holds only the shared {0}, so nothing else loses its discount.", [unit]);
			const disable_row = `<div class="prc-opt">
				<button class="btn btn-sm prc-btn-danger prc-act" data-rule="${esc(c.rule)}" data-action="disable">
					<i class="fa fa-ban"></i> ${__("Disable rule {0}", [esc(c.rule)])}</button>
				<span class="prc-why">${lose}</span>
			</div>`;
			actions = remove_row + disable_row;
		}
		return `<div class="prc-card ${state ? "is-done" : ""}">
			<div class="prc-head">
				<a href="/app/pricing-rule/${encodeURIComponent(c.rule)}" target="_blank" rel="noopener"><b>${esc(c.rule)}</b></a>
				<span class="prc-title">${esc(c.title || "")}</span>
				<span class="prc-spacer"></span>
				<span class="prc-disc">${esc(c.discount)}</span>
			</div>
			<div class="prc-meta">${esc(c.parties)} · ${__("priority")} ${c.priority || __("none")}
				· ${c.valid_from ? frappe.datetime.str_to_user(c.valid_from) : "—"} → ${c.valid_upto ? frappe.datetime.str_to_user(c.valid_upto) : __("no end")}
				${c.price_list ? " · " + esc(c.price_list) : ""}</div>
			<div class="prc-shared">${__("Also covers")} ${shared} <span class="text-muted">(${__("{0} of its {1}", [n, c.total])})</span></div>
			<div class="prc-actions">${actions}</div>
		</div>`;
	}

	function render() {
		const open = conflicts.filter((c) => !done[c.rule]);
		const p = res.suggested_priority;
		d.fields_dict.body.$wrapper.html(`
			<style>
				.prc-intro { font-size: 13px; margin-bottom: 12px; color: var(--text-muted); }
				.prc-card { border: 1px solid var(--border-color); border-radius: 8px; padding: 10px 12px; margin-bottom: 10px; }
				.prc-card.is-done { opacity: .65; background: var(--bg-light-gray, var(--control-bg)); }
				.prc-head { display: flex; align-items: center; gap: 8px; }
				.prc-title { color: var(--text-muted); }
				.prc-spacer { flex: 1; }
				.prc-disc { font-weight: 600; }
				.prc-meta { font-size: 12px; color: var(--text-muted); margin-top: 2px; }
				.prc-shared { font-size: 12px; margin-top: 6px; line-height: 1.8; }
				.prc-shared code { font-size: 11px; }
				.prc-actions { display: flex; flex-direction: column; gap: 6px; margin-top: 10px; }
				.prc-opt { display: flex; align-items: center; gap: 10px; flex-wrap: wrap; }
				.prc-opt .btn { min-width: 230px; text-align: left; }
				.prc-opt .btn i { margin-right: 4px; }
				.prc-opt.is-off .prc-why { font-style: italic; }
				.prc-btn-danger { color: var(--red-600, #c53030); border: 1px solid var(--red-300, #feb2b2); background: var(--red-50, #fff5f5); }
				.prc-btn-danger:hover, .prc-btn-danger:focus { color: #fff; background: var(--red-600, #c53030); border-color: var(--red-600, #c53030); }
				.prc-why { font-size: 12px; color: var(--text-muted); flex: 1; min-width: 200px; }
				.prc-prio { border-top: 1px solid var(--border-color); margin-top: 14px; padding-top: 12px; display: flex; align-items: center; gap: 12px; }
				.prc-prio p { margin: 0; font-size: 12px; color: var(--text-muted); flex: 1; }
			</style>
			<div class="prc-intro">${__("Two enabled rules with the same priority cover the same {0} for the same customers and dates. ERPNext would refuse every line they both match with “Multiple Price Rules exists with same criteria”. Fix each rule below, or let this rule win with a higher priority.", [prc_unit(frm.doc.apply_on, 1)])}</div>
			${conflicts.map(card).join("")}
			${open.length ? `<div class="prc-prio">
				<p>${p
					? __("Or keep the other rule(s) as they are and give <b>this</b> rule priority <b>{0}</b>: it then wins wherever both apply.", [p])
					: __("No priority up to 20 makes this rule win over all of them; fix the rules above instead.")}</p>
				${p ? `<button class="btn btn-sm btn-primary prc-prio-btn">${__("Set priority {0} and save", [p])}</button>` : ""}
			</div>` : ""}
		`);
	}

	d.$wrapper.on("click", ".prc-act", function () {
		const rule = $(this).attr("data-rule");
		const action = $(this).attr("data-action");
		const c = conflicts.find((x) => x.rule === rule);
		const go = () => {
			frappe.call({
				method: PRC_API + "resolve_conflict",
				args: { rule: rule, action: action, targets: JSON.stringify(c.shared) },
				freeze: true,
				callback: () => {
					done[rule] = action === "disable" ? "disabled" : "removed";
					frappe.show_alert({ message: action === "disable" ? __("{0} disabled", [rule]) : __("Removed from {0}", [rule]), indicator: "green" });
					if (conflicts.every((x) => done[x.rule])) {
						d.hide();
						frm.save();
					} else {
						render();
					}
				},
			});
		};
		if (action === "disable") {
			const others = c.total - c.shared.length;
			frappe.confirm(
				__("Disable pricing rule {0}?", [rule.bold() + (c.title ? " · " + frappe.utils.escape_html(c.title) : "")])
				+ "<br>" + __("Its discount: {0}", [c.discount])
				+ "<br><br>"
				+ (others > 0
					? __("All {0} {1} in it lose this discount, including the {2} not shared with the rule you are saving. To keep those, use <b>Remove</b> instead.", [c.total, prc_unit(c.apply_on, c.total), others])
					: __("It holds only the shared {0}, so nothing else is affected.", [prc_unit(c.apply_on, c.total)]))
				+ "<br>" + __("You can enable it again later from the rule itself."),
				go
			);
		} else {
			go();
		}
	});
	d.$wrapper.on("click", ".prc-prio-btn", function () {
		d.hide();
		frm.set_value("priority", String(res.suggested_priority)).then(() => frm.save());
	});
	// Links to other rules open in a new tab; the v13 router would otherwise take over this one.
	d.$wrapper.on("click", "a[target=_blank]", function (e) {
		e.preventDefault();
		e.stopPropagation();
		window.open(this.href, "_blank", "noopener");
	});

	render();
	d.show();
}
